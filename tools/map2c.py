#!/usr/bin/env python3
"""map2c.py — compile a docs/maps/*.json control map into firmware/map.c.

The JSON map (docs/map-convention.md) is the single source of truth shared by
the web shim and the firmware. The firmware never parses JSON: this tool bakes
the map into a const C table at build time.

Usage: map2c.py <map.json> [-o out.c]     (default stdout; build.sh writes
firmware/map_data.c -- pure generated data, accessors live in firmware/map.c)

Generated symbols (declared in firmware/map.h):
  MAP_ENC_CC[8]      encoder i -> CC number (from inputs.ccs "knob:i")
  MAP_BTN_NOTE[3]    transport PLAY/STOP/REC note (from inputs.notes
                     "button:play/stop/rec", else spec §4 defaults 36/37/38)
  MAP_LED            outputs.ledGrid: present? lo, hi CC range (bitmap rows)
  MAP_MIRROR         outputs.keyLeds.noteOn == "mirror"
Absent map entries -> disabled/default (partial maps are valid, convention v0.1).
"""
import json
import re
import sys

DEF_BTN = (36, 37, 38)  # spec §4: PLAY/STOP/REC


def knob_ccs(inputs):
    ccs = inputs.get("ccs", {}) or {}
    out = [0] * 8
    for cc, target in ccs.items():
        m = re.fullmatch(r"knob:([0-7])", str(target))
        if m:
            out[int(m.group(1))] = int(cc)
    return out


def btn_notes(inputs):
    notes = inputs.get("notes", {}) or {}
    out = [36, 37, 38]
    for i, name in enumerate(("play", "stop", "rec")):
        for cc, target in notes.items():
            if str(target) == f"button:{name}":
                out[i] = int(cc)
    return out


def led_cfg(outputs):
    lg = (outputs or {}).get("ledGrid", {}) or {}
    rng = lg.get("cc")
    if isinstance(rng, list) and len(rng) == 2:
        lo, hi = int(rng[0]), int(rng[1])
        return 1, lo, hi
    return 0, 0, 0


def generate(map_dict, map_path):
    inputs = map_dict.get("inputs", {}) or {}
    outputs = map_dict.get("outputs", {}) or {}

    enc = knob_ccs(inputs)
    btn = btn_notes(inputs)
    present, lo, hi = led_cfg(outputs)
    mirror = 1 if (outputs or {}).get("keyLeds", {}).get("noteOn") == "mirror" else 0

    lines = [
        "/* GENERATED by tools/map2c.py from %s -- do not edit by hand." % map_path,
        " * Regenerate: python3 tools/map2c.py %s -o firmware/map_data.c */" % map_path,
        '#include "map.h"',
        "",
        "const uint8_t MAP_ENC_CC[8] = { %s };" % ", ".join(str(c) for c in enc),
        "const uint8_t MAP_BTN_NOTE[3] = { %s };" % ", ".join(str(c) for c in btn),
        "const map_led_cfg_t MAP_LED = { %d, %u, %u };" % (present, lo, hi),
        "const uint8_t MAP_MIRROR = %d;" % mirror,
        "",
    ]
    return "\n".join(lines)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    map_path = sys.argv[1]
    out_path = None
    if len(sys.argv) >= 4 and sys.argv[2] == "-o":
        out_path = sys.argv[3]
    with open(map_path) as f:
        d = json.load(f)
    text = generate(d, map_path)
    if out_path:
        with open(out_path, "w") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()

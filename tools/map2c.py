#!/usr/bin/env python3
"""map2c.py — compile a docs/maps/*.json control map into firmware/map_data.c.

The JSON map (docs/map-convention.md) is the single source of truth shared by
the web shim and the firmware. The firmware never parses JSON: this tool bakes
the map into const C tables at build time.

Usage: map2c.py <map.json> [-o out.c]     (default stdout; build.sh writes
firmware/map_data.c -- pure generated data, accessors live in firmware/map.c)

Generated symbols (declared in firmware/map.h):
  MAP_ENC_CC[7]      encoder i -> CC number (inputs.ccs "knob:i", i=0..6)
  MAP_BTN_CC[14]     button i -> CC number (inputs.ccs "btn:i", i=0..13 in
                     panel order FX SEL ENV LFO EDIT GLO HOME SAVE ARP SEQ
                     PLAY REC OCT- OCT+; default 40+i)
  MAP_LED            outputs.ledGrid: present? lo, hi CC range (bitmap rows)
  MAP_MIRROR         outputs.keyLeds.noteOn == "mirror"
Absent map entries -> disabled/default (partial maps are valid, convention v0.1).
"""
import json
import re
import sys

DEF_BTN_CC0 = 40  # spec §4 (2026-10-14): 14 buttons -> CC 40..53
BTN_ORDER = ["FX", "SEL", "ENV", "LFO", "EDIT", "GLO", "HOME", "SAVE",
             "ARP", "SEQ", "PLAY", "REC", "OCTDN", "OCTUP"]


def knob_ccs(inputs):
    ccs = inputs.get("ccs", {}) or {}
    out = [0] * 7
    for cc, target in ccs.items():
        m = re.fullmatch(r"knob:([0-6])", str(target))
        if m:
            out[int(m.group(1))] = int(cc)
    return out


def btn_ccs(inputs):
    ccs = inputs.get("ccs", {}) or {}
    out = [DEF_BTN_CC0 + i for i in range(14)]
    for cc, target in ccs.items():
        m = re.fullmatch(r"btn:([0-9]|1[0-3])", str(target))
        if m:
            out[int(m.group(1))] = int(cc)
    return out


def led_cfg(outputs):
    lg = (outputs or {}).get("ledGrid", {}) or {}
    rng = lg.get("cc")
    if isinstance(rng, list) and len(rng) == 2:
        return 1, int(rng[0]), int(rng[1])
    return 0, 0, 0


def generate(map_dict, map_path):
    inputs = map_dict.get("inputs", {}) or {}
    outputs = map_dict.get("outputs", {}) or {}

    enc = knob_ccs(inputs)
    btn = btn_ccs(inputs)
    present, lo, hi = led_cfg(outputs)
    mirror = 1 if (outputs or {}).get("keyLeds", {}).get("noteOn") == "mirror" else 0

    return "\n".join([
        "/* GENERATED by tools/map2c.py from %s -- do not edit by hand." % map_path,
        " * Regenerate: python3 tools/map2c.py %s -o firmware/map_data.c */" % map_path,
        '#include "map.h"',
        "",
        "const uint8_t MAP_ENC_CC[MAP_NENC] = { %s };" % ", ".join(map(str, enc)),
        "const uint8_t MAP_BTN_CC[MAP_NBTN] = { %s };" % ", ".join(map(str, btn)),
        "const map_led_cfg_t MAP_LED = { %d, %u, %u };" % (present, lo, hi),
        "const uint8_t MAP_BTN_LED0 = %u;" % (outputs.get("btnLeds", {}).get("cc", [54, 67])[0]),
        "const uint8_t MAP_MIRROR = %d;" % mirror,
        "",
    ])


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    map_path = sys.argv[1]
    out_path = sys.argv[3] if len(sys.argv) >= 4 and sys.argv[2] == "-o" else None
    with open(map_path) as f:
        d = json.load(f)
    text = generate(d, map_path)
    if out_path:
        with open(out_path, "w") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
